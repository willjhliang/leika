"""Regenerate the files derived from other sources.

- `client/src/WebsocketMessages.ts` from the Python message dataclasses;
- `client/src/VersionInfo.ts` from `leika.__version__`;
- the `Icon` enum and SVG archive from the client's `lucide-static` package,
  which stays on the same version as `lucide-react`.

`make generate` rewrites whatever is out of date and `make check-generated`
fails instead. Both need the client's `npm ci` for Prettier and the icons.
"""

from __future__ import annotations

import argparse
import io
import subprocess
import zipfile
from pathlib import Path

import leika
import leika.infra
from leika._messages import Message

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src/leika"
CLIENT = PACKAGE / "client"
PRETTIER = CLIENT / "node_modules/.bin/prettier"
LUCIDE_ICONS = CLIENT / "node_modules/lucide-static/icons"


def _prettier(path: Path, source: str) -> str:
    """Format generated TypeScript exactly as the checked-in client is formatted."""
    return subprocess.run(
        [str(PRETTIER), "--stdin-filepath", str(path)],
        cwd=CLIENT,
        input=source,
        stdout=subprocess.PIPE,
        text=True,
        check=True,
    ).stdout


def _typescript() -> dict[Path, str]:
    messages = (
        leika.infra.generate_typescript_interfaces(Message) + "\n"
        "/** Hash of the message schema this bundle was built against. Sent with\n"
        " * the version at connect, so a server running different code is turned\n"
        " * away with a reason instead of feeding the page fields it cannot read. */\n"
        f'export const LEIKA_PROTOCOL = "{leika.infra.protocol_fingerprint(Message)}";\n'
    )
    version = (
        "// Generated by scripts/generate.py; do not edit manually.\n"
        f'export const LEIKA_VERSION = "{leika.__version__}";\n'
    )
    outputs = {
        CLIENT / "src/WebsocketMessages.ts": messages,
        CLIENT / "src/VersionInfo.ts": version,
    }
    return {path: _prettier(path, source) for path, source in outputs.items()}


def enum_name_from_icon(name: str) -> str:
    """Capitalize an icon name for use as an enum name."""
    name = name.upper().replace("-", "_")
    return "ICON_" + name if name[0].isdigit() else name


def _icon_archive(sources: list[Path]) -> bytes:
    """Pack the SVGs with fixed metadata, so repacking the same icons is byte-stable."""
    archive = io.BytesIO()
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in sources:
            info = zipfile.ZipInfo(path.name, date_time=(1980, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, path.read_bytes())
    return archive.getvalue()


def _icon_enums(icon_names: list[str]) -> tuple[str, str]:
    """Return the `Icon` stub and runtime source."""
    header_doc = [
        "# Automatically generated by `scripts/generate.py`",
        "# Icons from Lucide (https://lucide.dev), ISC licensed.",
    ]
    summary = "'Enum' class for referencing Lucide icons."
    # Why this isn't an enum belongs next to the code rather than in the
    # docstring, which is published as user-facing API documentation.
    class_comment = [
        "# Not an enum.Enum subclass: importing an enum with thousands of names can cost",
        "# hundreds of milliseconds at import time.",
    ]
    stub = header_doc + [
        "from typing import NewType",
        "",
        'IconName = NewType("IconName", str)',
        '"""Name of an icon. Should be generated via `leika.Icon.*`."""',
        "",
        *class_comment,
        "class Icon:",
        f'    """{summary}"""',
        "",
        *(f'    {enum_name_from_icon(icon)}: IconName = IconName("{icon}")' for icon in icon_names),
    ]
    source = header_doc + [
        "from typing import NewType",
        "",
        'IconName = NewType("IconName", str)',
        '"""Name of an icon. Should be generated via `leika.Icon.*`."""',
        "",
        "",
        "class _IconStringConverter(type):",
        "    def __getattr__(self, __name: str) -> IconName:",
        '        if not __name.startswith("_"):',
        '            return IconName(__name.lower().replace("_", "-"))',
        "        else:",
        "            raise AttributeError()",
        "",
        "",
        *class_comment,
        "class Icon(metaclass=_IconStringConverter):",
        f'    """{summary}',
        "",
        "    Attributes:",
        *(
            f"        {enum_name_from_icon(icon)} (IconName): The :code:`{icon}` icon."
            for icon in icon_names
        ),
        '    """',
    ]
    return "\n".join(stub) + "\n", "\n".join(source) + "\n"


def _icons() -> dict[Path, bytes | str]:
    sources = sorted(LUCIDE_ICONS.glob("*.svg"))
    if not sources:
        raise SystemExit(f"no icons in {LUCIDE_ICONS}; run `npm ci` in src/leika/client.")
    stub, source = _icon_enums([path.stem for path in sources])
    return {
        PACKAGE / "_icons/lucide-icons.zip": _icon_archive(sources),
        PACKAGE / "_icons_enum.pyi": stub,
        PACKAGE / "_icons_enum.py": source,
    }


def _is_current(path: Path, content: bytes) -> bool:
    if not path.is_file():
        return False
    if path.suffix != ".zip":
        return path.read_bytes() == content

    # Compare members, not bytes: zlib builds may deflate the same icons differently.
    def members(data: bytes) -> list[tuple[str, bytes]]:
        with zipfile.ZipFile(io.BytesIO(data)) as zf:
            return [(name, zf.read(name)) for name in zf.namelist()]

    return members(path.read_bytes()) == members(content)


def main() -> int:
    parser = argparse.ArgumentParser(description="Regenerate the files derived from other sources.")
    parser.add_argument("--check", action="store_true", help="fail if any file is out of date")
    args = parser.parse_args()
    if not PRETTIER.is_file():
        raise SystemExit(f"{PRETTIER} is missing; run `npm ci` in src/leika/client.")

    stale = 0
    for path, content in {**_typescript(), **_icons()}.items():
        data = content.encode() if isinstance(content, str) else content
        if _is_current(path, data):
            continue
        stale += 1
        if args.check:
            print(f"out of date: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(data)
            print(f"updated: {path.relative_to(ROOT)}")
    if args.check and stale:
        print("run `make generate` to update them")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
