"""Named pages, each with an independent pane registry and saved layout."""

from __future__ import annotations

import threading
import uuid
from collections.abc import Iterator
from typing import TYPE_CHECKING, NewType, cast

from . import _messages
from ._panes import Panes
from ._validation import validate_layout_id, validate_renderer_string

if TYPE_CHECKING:
    from ._server import Server


PageId = NewType("PageId", str)

_DEFAULT_PAGE_ID = "default"
_DEFAULT_PAGE_NAME = "Main"


def _validate_page_name(value: object) -> str:
    name = cast(str, validate_renderer_string(value, "page name"))
    if not name:
        raise ValueError("page name must not be empty.")
    return name


def _page_name_from_label(value: object) -> str:
    """The default page's name for an optional ``label``."""

    if value is None or value == "":
        return _DEFAULT_PAGE_NAME
    return _validate_page_name(value)


class Page:
    """One named page and the panes whose layout its viewers arrange."""

    def __init__(self, owner: Pages, page_id: str, name: str, panes: Panes) -> None:
        self._owner = owner
        self._page_id = page_id
        self._name = name
        self.panes = panes
        """Pane API scoped to this page."""

    @property
    def page_id(self) -> PageId:
        """Stable identifier used to persist this page's browser layout."""

        return PageId(self._page_id)

    @property
    def name(self) -> str:
        """Unique name displayed in the page selector."""

        with self._owner._lock:
            return self._name

    @name.setter
    def name(self, value: str) -> None:
        self._owner._rename(self, _validate_page_name(value))


class Pages:
    """Declare the named pages in a Leika workspace.

    Every server starts with :attr:`default`. Use :meth:`add` for additional
    pages. Pane IDs are local to their page.
    """

    def __init__(self, owner: Server, default_name: str) -> None:
        self._owner = owner
        self._lock = threading.RLock()
        self._page_from_page_id: dict[str, Page] = {}
        self.default = self._add(default_name, _DEFAULT_PAGE_ID, is_default=True)
        """The default page, whose panes are also ``server.panes``."""

    def _check_name_available(self, name: str, *, excluding: Page | None = None) -> None:
        with self._lock:
            if any(
                page is not excluding and page._name == name
                for page in self._page_from_page_id.values()
            ):
                raise ValueError(f"Page name {name!r} already exists.")

    def _add(self, name: str, page_id: str, *, is_default: bool) -> Page:
        with self._lock:
            if page_id in self._page_from_page_id:
                raise ValueError(f"Page ID {page_id!r} already exists.")
            self._check_name_available(name)
            panes = Panes(self._owner, page_id)
            self._owner._websock_server.queue_messages_or_raise(
                (
                    _messages.PageCreateMessage(
                        page_id=page_id,
                        name=name,
                        is_default=is_default,
                    ),
                    panes._snapshot_message(),
                    _messages.PageCatalogMessage(
                        page_ids=tuple(self._page_from_page_id) + (page_id,)
                    ),
                )
            )
            page = Page(self, page_id, name, panes)
            self._page_from_page_id[page_id] = page
            return page

    def add(self, name: str, *, page_id: str | None = None) -> Page:
        """Add a page and return its page-scoped pane API.

        Args:
            name: Unique name displayed in the page selector.
            page_id: Stable layout identity. A UUID is generated by default;
                pass an explicit value to restore layouts across restarts.

        Returns:
            The new page.
        """

        name = _validate_page_name(name)
        resolved_page_id = (
            str(uuid.uuid4()) if page_id is None else validate_layout_id(page_id, "Page ID")
        )
        return self._add(name, resolved_page_id, is_default=False)

    def _rename(self, page: Page, name: str) -> None:
        with self._lock:
            if page._name == name:
                return
            self._check_name_available(name, excluding=page)
            self._owner._websock_server.queue_message_or_raise(
                _messages.PageUpdateMessage(page_id=page._page_id, name=name)
            )
            page._name = name

    def __len__(self) -> int:
        with self._lock:
            return len(self._page_from_page_id)

    def __iter__(self) -> Iterator[Page]:
        with self._lock:
            return iter(tuple(self._page_from_page_id.values()))
